    public static function isSuccessful(int|string|null $code): bool
    {
        return self::normalize($code) === self::SUCCESS;
    }

    public static function message(int|string|null $code): string
    {
        return self::MESSAGES[self::normalize($code)] ?? 'خطای ناشناخته ای رخ داده است';
    }

    /**
     * The gateway answers "00" for success but other codes are sent both
     * zero-padded ("05") and plain ("5"), and sometimes as integers.
     */
    public static function normalize(int|string|null $code): string
    {
        $code = trim((string) $code);

        if ($code === '' || ! ctype_digit($code)) {
            return $code;
        }

        $code = ltrim($code, '0');

        return $code === '' ? self::SUCCESS : $code;
    }
